import mongoose from 'mongoose'

const transactionSchema = new mongoose.Schema(
  {
    // Phase 4.1: owning user. Set only by the server from the authenticated session.
    // Legacy documents created before authentication have no userId and are therefore
    // invisible to every user-scoped query until explicitly migrated.
    userId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
    date: { type: Date, required: true },
    merchant: { type: String, required: true, trim: true },
    amount: { type: Number, required: true, min: 0 },
    account: { type: String, trim: true, default: 'Manual Entry' },
    category: { type: String, trim: true, default: 'General' },
    isRecurring: { type: Boolean, default: false },
    subscriptionId: { type: String, trim: true },
    notes: { type: String, trim: true },
    // Phase 5.1: bank/statement reference id from a CSV import, when the file provides one.
    // Used only to make re-imports idempotent; never generated by SubSense.
    reference: { type: String, trim: true, maxlength: 200 },
  },
  { timestamps: true },
)

transactionSchema.index({ userId: 1, date: -1 })
transactionSchema.index({ userId: 1, subscriptionId: 1 })

export const Transaction = mongoose.model('Transaction', transactionSchema)
