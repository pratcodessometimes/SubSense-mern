"""
Central configuration for the SubSense ML dataset pipeline (Phase 3.1).

Every threshold used by preprocessing and feature engineering lives here so
that (a) it is documented in one place and (b) changing it is a deliberate,
reviewable decision rather than a magic number hidden in a function.
"""

# ---------------------------------------------------------------------------
# Currency policy
# ---------------------------------------------------------------------------
# The MongoDB Transaction schema has NO currency field, and the existing
# backend/frontend format every amount with the ₹ symbol. We therefore assume
# every amount is INR. If an input file carries a `currency` column, rows in
# any other currency are EXCLUDED (with a reason) instead of being silently
# mixed, because we have no reliable exchange-rate source.
BASE_CURRENCY = "INR"

# ---------------------------------------------------------------------------
# Date policy
# ---------------------------------------------------------------------------
# All dates are converted to UTC and truncated to a calendar day. This matches
# the backend, where `new Date('2026-06-14')` is interpreted as UTC midnight.
# Accepted formats are listed explicitly; anything else is rejected rather
# than guessed. Day-first formats follow the Indian DD/MM/YYYY convention.
ACCEPTED_DATE_FORMATS = (
    "%Y-%m-%d",            # 2026-06-14       (ISO, used by sample CSV)
    "%Y/%m/%d",            # 2026/06/14
    "%d-%m-%Y",            # 14-06-2026       (Indian day-first)
    "%d/%m/%Y",            # 14/06/2026       (Indian day-first)
    "%d %b %Y",            # 14 Jun 2026
    "%d %B %Y",            # 14 June 2026
)
# ISO-8601 timestamps with a time and/or offset (2026-06-14T10:00:00Z,
# 2026-06-14T23:30:00+05:30) are also accepted and converted to UTC first.

# ---------------------------------------------------------------------------
# Interval / periodicity thresholds (days)
# ---------------------------------------------------------------------------
# Kept identical to backend/src/services/detectionService.js so the ML features
# and the rule-based baseline speak the same language.
MONTHLY_INTERVAL_MIN = 24
MONTHLY_INTERVAL_MAX = 36
YEARLY_INTERVAL_MIN = 340
YEARLY_INTERVAL_MAX = 390
NOMINAL_MONTH_DAYS = 30.44   # 365.25 / 12
NOMINAL_YEAR_DAYS = 365.25

# An interval this many times longer than the median interval counts as a
# "missed cycle" (gap) in the payment history.
GAP_MULTIPLIER = 1.5

# Coefficient of variation of intervals above which history is "irregular".
IRREGULAR_INTERVAL_CV = 0.25

# Two amounts are considered "the same price" if within this relative tolerance.
AMOUNT_EQUAL_TOLERANCE = 0.01

# ---------------------------------------------------------------------------
# History sufficiency
# ---------------------------------------------------------------------------
# At least 2 distinct payment dates are needed to compute ONE interval.
MIN_DATES_FOR_INTERVALS = 2
# The rule engine treats >= 3 payments as a "strong" cadence; we reuse that.
SUFFICIENT_HISTORY_DATES = 3

# ---------------------------------------------------------------------------
# Labels
# ---------------------------------------------------------------------------
LABELS = ("subscription", "non_subscription", "ambiguous")

# Where a label came from. Ordered from most to least trustworthy.
LABEL_SOURCES = (
    "verified",          # independently verified (e.g. bank/merchant statement)
    "user_confirmed",    # the user explicitly confirmed it in the app
    "rule_provisional",  # produced by the existing rule engine (circular!)
    "synthetic",         # generated by our synthetic data generator
    "unlabeled",         # no label available
)

# Columns that must NEVER be used as model inputs because they encode (or are
# produced from) the label, or are raw identifiers.
FORBIDDEN_FEATURE_COLUMNS = (
    "isRecurring",
    "is_recurring",
    "subscriptionId",
    "subscription_id",
    "status",
    "confidence",
    "label",
    "label_source",
    "archetype",
    "category",        # user/normalizer supplied; strongly label-correlated
    "group_id",
    "user_id",
    "merchant_key",
    "merchant_name",
    "account",
    "reference",
)
